-- ------------------------------------------------------------
-- 1. MASTER DATA: SKUS, PACKAGING & LOTS
-- ------------------------------------------------------------

CREATE TYPE uom AS ENUM (
    'EACH',
    'Kg',
    'g',
    'm',
    'L',
    'mL'
);

CREATE TABLE stock_keeping_units (
    id bigint 
        GENERATED ALWAYS AS IDENTITY (START WITH 10000) 
        PRIMARY KEY,
    name text NOT NULL,
    base_uom uom NOT NULL DEFAULT 'EACH',
    is_discrete boolean NOT NULL DEFAULT true,
    requires_lot_tracking boolean NOT NULL DEFAULT false,
    tenant_id bigint,
    attributes jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_skus_name_trgm ON stock_keeping_units USING gin (name gin_trgm_ops);
CREATE INDEX idx_skus_attributes ON stock_keeping_units USING gin (attributes);

CREATE TABLE sku_packaging_units (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    sku_id bigint NOT NULL REFERENCES stock_keeping_units(id) ON DELETE CASCADE,
    unit_name text NOT NULL,
    conversion_factor numeric(12, 4) NOT NULL CHECK (conversion_factor > 0),
    parent_packaging_unit_id bigint,
    is_base_unit boolean NOT NULL DEFAULT false,
    allows_break_bulk boolean NOT NULL DEFAULT false,
    barcode text COLLATE "C" UNIQUE,
    tare_weight_kg numeric(10, 3) CHECK (tare_weight_kg >= 0),
    gross_volume_cm3 numeric(12, 2) CHECK (gross_volume_cm3 > 0),

    CONSTRAINT uq_sku_unit_name UNIQUE (sku_id, unit_name),
    CONSTRAINT uq_sku_packaging_units_id_sku UNIQUE (id, sku_id),

    CONSTRAINT chk_base_unit_factor CHECK (
        NOT is_base_unit OR conversion_factor = 1.0000
    ),
    CONSTRAINT fk_pku_same_sku_parent 
        FOREIGN KEY (parent_packaging_unit_id, sku_id) 
        REFERENCES sku_packaging_units(id, sku_id) 
        ON DELETE RESTRICT,
    CONSTRAINT chk_base_unit_no_parent CHECK (
        NOT is_base_unit OR parent_packaging_unit_id IS NULL
    ),
    CONSTRAINT chk_no_self_parent CHECK (
        parent_packaging_unit_id IS NULL OR parent_packaging_unit_id != id
    )
);

CREATE UNIQUE INDEX uq_sku_single_base_unit 
    ON sku_packaging_units (sku_id) 
    WHERE is_base_unit = true;

CREATE INDEX idx_packaging_units_sku ON sku_packaging_units (sku_id);

CREATE TYPE lot_status AS ENUM (
    'AVAILABLE',
    'QUARANTINED',
    'EXPIRED',
    'RECALLED'
);

CREATE TABLE lots (
    id bigint 
        GENERATED ALWAYS AS IDENTITY 
        PRIMARY KEY,
    sku_id bigint NOT NULL 
        REFERENCES stock_keeping_units(id) 
        ON DELETE RESTRICT,
    lot_number text COLLATE "C" NOT NULL,
    status lot_status NOT NULL DEFAULT 'AVAILABLE',
    manufactured_at date,
    expires_at date,
    received_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_sku_lot_number UNIQUE (sku_id, lot_number),
    CONSTRAINT uq_sku_lot_id UNIQUE (id, sku_id)
);

CREATE INDEX idx_lots_expiration ON lots (expires_at) WHERE expires_at IS NOT NULL;
CREATE INDEX idx_lots_status ON lots (status);

-- ------------------------------------------------------------
-- 2. UNIFIED STORAGE HIERARCHY (BINS, PALLETS & TOTES)
-- ------------------------------------------------------------

CREATE TYPE storage_node_type AS ENUM (
    'WAREHOUSE',
    'ZONE',
    'AISLE',
    'BAY',
    'BIN',       -- Immobile physical locations
    'PALLET',
    'TOTE',
    'CART'       -- Mobile handling units
);

CREATE TABLE storage_nodes (
    id bigint 
        GENERATED BY DEFAULT AS IDENTITY 
        PRIMARY KEY,
    parent_id bigint 
        REFERENCES storage_nodes(id) 
        ON DELETE RESTRICT,
    path ltree,
    code text COLLATE "C" NOT NULL UNIQUE,
    node_type storage_node_type NOT NULL DEFAULT 'BIN',
    is_movable boolean NOT NULL DEFAULT false,
    max_weight_kg numeric(10, 2) CHECK (max_weight_kg > 0),
    max_volume_cm3 numeric(12, 2) CHECK (max_volume_cm3 > 0),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_storage_nodes_path_gist ON storage_nodes USING gist (path);
CREATE INDEX idx_storage_nodes_path_btree ON storage_nodes (path);
CREATE INDEX idx_storage_nodes_parent_id ON storage_nodes (parent_id);
CREATE INDEX idx_storage_nodes_type ON storage_nodes (node_type);

-- ------------------------------------------------------------
-- 3. INVENTORY BALANCES
-- ------------------------------------------------------------

CREATE TABLE inventory_balances (
    id bigint 
        GENERATED ALWAYS AS IDENTITY 
        PRIMARY KEY,
    node_id bigint NOT NULL 
        REFERENCES storage_nodes(id) 
        ON DELETE RESTRICT,
    sku_id bigint NOT NULL 
        REFERENCES stock_keeping_units(id) 
        ON DELETE RESTRICT,
    pku_id bigint NOT NULL,
    lot_id bigint,

    is_sealed boolean NOT NULL DEFAULT true,
    package_count numeric(12, 4) NOT NULL CHECK (package_count >= 0),

    -- version for OCC
    version int NOT NULL DEFAULT 1,

    -- Quantities always stored in the SKU's atomic base UOM
    on_hand numeric(12, 4) NOT NULL DEFAULT 0,
    allocated numeric(12, 4) NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_on_hand_positive CHECK (on_hand >= 0),
    CONSTRAINT chk_allocated_positive CHECK (allocated >= 0),
    CONSTRAINT chk_allocated_le_on_hand CHECK (allocated <= on_hand),
    CONSTRAINT chk_unsealed_no_packages 
      CHECK (is_sealed OR package_count = 0),

    -- Composite foreign keys prevent cross-SKU lot/PKU mixing
    CONSTRAINT fk_balance_pku 
        FOREIGN KEY (pku_id, sku_id) 
        REFERENCES sku_packaging_units(id, sku_id) 
        ON DELETE RESTRICT,
    CONSTRAINT fk_balance_lot 
        FOREIGN KEY (lot_id, sku_id) 
        REFERENCES lots(id, sku_id) 
        ON DELETE RESTRICT,

    CONSTRAINT uq_balance_id_sku UNIQUE (id, sku_id)
);

ALTER TABLE inventory_balances SET (fillfactor = 70);

-- Unique entry per Node + PKU + Lot + Sealed State
CREATE UNIQUE INDEX uq_node_inventory 
    ON inventory_balances (node_id, pku_id, lot_id, is_sealed) NULLS NOT DISTINCT;

CREATE INDEX idx_balances_reservable 
    ON inventory_balances (sku_id, pku_id, is_sealed, lot_id);

CREATE INDEX idx_balances_node ON inventory_balances (node_id);

-- ------------------------------------------------------------
-- 4. OUTBOUND DEMAND & ALLOCATION ENGINE
-- ------------------------------------------------------------

CREATE TYPE order_status AS ENUM (
    'PENDING',
    'ALLOCATED',
    'PARTIALLY_ALLOCATED',
    'PICKING',
    'PACKED',
    'SHIPPED',
    'CANCELLED'
);

CREATE TABLE outbound_orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id bigint,
    order_number text COLLATE "C" NOT NULL UNIQUE,
    version integer NOT NULL DEFAULT 1,
    customer_name text,
    status order_status NOT NULL DEFAULT 'PENDING',
    priority integer NOT NULL DEFAULT 100,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_orders_status_priority 
    ON outbound_orders (status, priority DESC, created_at ASC);

CREATE TABLE outbound_order_lines (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL 
        REFERENCES outbound_orders(id) 
        ON DELETE CASCADE,
    sku_id bigint NOT NULL 
        REFERENCES stock_keeping_units(id) 
        ON DELETE RESTRICT,
    pku_id bigint NOT NULL,
    requested_quantity numeric(12, 4) NOT NULL CHECK (requested_quantity > 0),
    fulfilled_quantity numeric(12, 4) NOT NULL DEFAULT 0 CHECK (fulfilled_quantity >= 0),

    CONSTRAINT fk_order_line_pku 
        FOREIGN KEY (pku_id, sku_id) 
        REFERENCES sku_packaging_units(id, sku_id) 
        ON DELETE RESTRICT,
    CONSTRAINT uq_order_line_pku UNIQUE (order_id, pku_id),
    CONSTRAINT uq_order_line_id_sku UNIQUE (id, sku_id),
    CONSTRAINT chk_fulfillment_bounds CHECK (fulfilled_quantity <= requested_quantity)
);

CREATE INDEX idx_order_lines_order ON outbound_order_lines (order_id);
CREATE INDEX idx_order_lines_sku ON outbound_order_lines (sku_id);
CREATE INDEX idx_order_lines_pku ON outbound_order_lines (pku_id);

CREATE TABLE inventory_allocations (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    order_line_id bigint NOT NULL,
    balance_id bigint NOT NULL,
    sku_id bigint NOT NULL,

    allocated_quantity numeric(12, 4) NOT NULL CHECK (allocated_quantity > 0),
    picked_quantity numeric(12,4) NOT NULL DEFAULT 0 CHECK (picked_quantity >=0),
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_alloc_order_line 
        FOREIGN KEY (order_line_id, sku_id) 
        REFERENCES outbound_order_lines(id, sku_id) 
        ON DELETE CASCADE,

    -- Guarantees the allocation pulls from a balance of the SAME SKU
    CONSTRAINT fk_alloc_balance 
        FOREIGN KEY (balance_id, sku_id) 
        REFERENCES inventory_balances(id, sku_id) 
        ON DELETE RESTRICT,

    CONSTRAINT uq_order_line_balance UNIQUE (order_line_id, balance_id),
    CONSTRAINT chk_picked_le_allocated CHECK (picked_quantity <= allocated_quantity)
);

CREATE INDEX idx_allocations_order_line ON inventory_allocations (order_line_id);
CREATE INDEX idx_allocations_balance ON inventory_allocations (balance_id);

