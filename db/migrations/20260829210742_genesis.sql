CREATE TYPE inbound_order_status AS ENUM (
    'DRAFT',
    'ISSUED',
    'PARTIALLY_RECEIVED',
    'RECEIVED',
    'CANCELLED'
);

CREATE TABLE inbound_orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    po_number text COLLATE "C" NOT NULL UNIQUE,
    tenant_id bigint,
    vendor_name text NOT NULL,
    version integer NOT NULL DEFAULT 1,
    status inbound_order_status NOT NULL DEFAULT 'ISSUED',
    expected_delivery date,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE inbound_order_lines (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    inbound_order_id bigint NOT NULL 
        REFERENCES inbound_orders(id) 
        ON DELETE CASCADE,
    sku_id bigint NOT NULL 
        REFERENCES stock_keeping_units(id) 
        ON DELETE RESTRICT,
    pku_id bigint NOT NULL,
    expected_quantity numeric(12, 4) NOT NULL CHECK (expected_quantity > 0),
    received_quantity numeric(12, 4) NOT NULL DEFAULT 0 CHECK (received_quantity >= 0),

    CONSTRAINT fk_po_line_pku 
        FOREIGN KEY (pku_id, sku_id) 
        REFERENCES sku_packaging_units(id, sku_id) 
        ON DELETE RESTRICT,
    CONSTRAINT uq_po_line_pku UNIQUE (inbound_order_id, pku_id)
);

CREATE INDEX idx_po_lines_po ON inbound_order_lines (inbound_order_id);
CREATE INDEX idx_po_lines_sku ON inbound_order_lines (sku_id);

CREATE TYPE task_type AS ENUM (
    'PUTAWAY',
    'PICK',
    'REPLENISH',
    'COUNT',
    'RELOCATE_NODE'
);

CREATE TYPE task_status AS ENUM (
    'PENDING',
    'ASSIGNED',
    'IN_PROGRESS',
    'COMPLETED',
    'CANCELLED'
);

CREATE TABLE warehouse_tasks (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    task_type task_type NOT NULL,
    status task_status NOT NULL DEFAULT 'PENDING',
    priority integer NOT NULL DEFAULT 100,

    -- Stock-level directives
    sku_id bigint REFERENCES stock_keeping_units(id) ON DELETE RESTRICT,
    pku_id bigint,
    lot_id bigint,
    package_count numeric(12, 4) CHECK (package_count > 0),
    quantity numeric(12, 4) CHECK (quantity > 0),

    -- Container-level directives (e.g. moving an entire pallet)
    target_node_id bigint REFERENCES storage_nodes(id) ON DELETE RESTRICT,

    source_node_id bigint REFERENCES storage_nodes(id) ON DELETE RESTRICT,
    destination_node_id bigint REFERENCES storage_nodes(id) ON DELETE RESTRICT,

    order_line_id bigint REFERENCES outbound_order_lines(id) ON DELETE SET NULL,
    allocation_id bigint REFERENCES inventory_allocations(id) ON DELETE SET NULL,

    assigned_operator_id text,
    created_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,

    CONSTRAINT fk_task_pku FOREIGN KEY (pku_id, sku_id)
        REFERENCES sku_packaging_units(id, sku_id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_lot FOREIGN KEY (lot_id, sku_id)
        REFERENCES lots(id, sku_id) ON DELETE RESTRICT,
    CONSTRAINT chk_task_sku_present CHECK (
        (pku_id IS NULL AND lot_id IS NULL) OR sku_id IS NOT NULL
    ),
    CONSTRAINT chk_task_payload CHECK (
        target_node_id IS NOT NULL OR (pku_id IS NOT NULL AND quantity IS NOT NULL)
    )
);

CREATE INDEX idx_tasks_execution ON warehouse_tasks (status, priority DESC, created_at ASC);
CREATE INDEX idx_tasks_operator ON warehouse_tasks (assigned_operator_id) WHERE assigned_operator_id IS NOT NULL;

CREATE TABLE node_relocations (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    node_id bigint NOT NULL REFERENCES storage_nodes(id) ON DELETE RESTRICT,
    from_parent_id bigint REFERENCES storage_nodes(id) ON DELETE RESTRICT,
    to_parent_id bigint REFERENCES storage_nodes(id) ON DELETE RESTRICT,
    from_path ltree NOT NULL,
    to_path ltree NOT NULL,
    operator_id text COLLATE "C" NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_relocations_node ON node_relocations (node_id, created_at DESC);

CREATE TYPE receipt_status AS ENUM (
    'RECEIVING',  -- Worker is currently scanning items on the dock
    'COMPLETED',  -- Truck is gone, inventory is confirmed
    'CANCELLED'
);

CREATE TABLE receipts (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    inbound_order_id bigint NOT NULL 
        REFERENCES inbound_orders(id) 
        ON DELETE RESTRICT,
    receipt_number text COLLATE "C" NOT NULL UNIQUE,
    status receipt_status NOT NULL DEFAULT 'RECEIVING',
    operator_id text COLLATE "C" NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE receipt_lines (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    receipt_id bigint NOT NULL 
        REFERENCES receipts(id) 
        ON DELETE CASCADE,
    inbound_order_line_id bigint 
        REFERENCES inbound_order_lines(id) 
        ON DELETE RESTRICT,
    
    -- The actual physical items counted
    sku_id bigint NOT NULL REFERENCES stock_keeping_units(id) ON DELETE RESTRICT,
    pku_id bigint NOT NULL,
    lot_id bigint,
    received_quantity numeric(12, 4) NOT NULL CHECK (received_quantity > 0),
    package_count numeric(12, 4) NOT NULL CHECK (package_count >= 0),
    
    -- Maintain strict composites
    CONSTRAINT fk_receipt_line_pku FOREIGN KEY (pku_id, sku_id) 
        REFERENCES sku_packaging_units(id, sku_id) ON DELETE RESTRICT,
    CONSTRAINT fk_receipt_line_lot FOREIGN KEY (lot_id, sku_id) 
        REFERENCES lots(id, sku_id) ON DELETE RESTRICT
);

CREATE INDEX idx_receipt_lines_receipt ON receipt_lines(receipt_id);

CREATE TYPE shipment_status AS ENUM (
    'STAGED',    -- Sitting on the outbound dock
    'SHIPPED',   -- Carrier picked it up
    'DELIVERED', -- Optional: Updated via carrier API webhooks
    'CANCELLED'
);

CREATE TABLE shipments (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shipment_number text COLLATE "C" NOT NULL UNIQUE,
    carrier_name text NOT NULL, -- e.g., 'FedEx', 'UPS', 'Internal Fleet'
    master_tracking_number text COLLATE "C",
    status shipment_status NOT NULL DEFAULT 'STAGED',
    shipped_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Handling Units represent physical boxes, pallets, or totes leaving the building
CREATE TABLE handling_units (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    outbound_order_id bigint NOT NULL 
        REFERENCES outbound_orders(id) 
        ON DELETE RESTRICT,
    shipment_id bigint 
        REFERENCES shipments(id) 
        ON DELETE SET NULL, -- A box is packed before it is assigned to a truck
        
    sscc text COLLATE "C" UNIQUE, -- Standard Serial Shipping Container Code barcode
    tracking_number text COLLATE "C", -- Box-level tracking label
    
    tare_weight_kg numeric(10, 3) DEFAULT 0 CHECK (tare_weight_kg >= 0),
    gross_weight_kg numeric(10, 3) DEFAULT 0 CHECK (gross_weight_kg >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Maps the internal warehouse allocation to the physical outbound box
CREATE TABLE handling_unit_contents (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    handling_unit_id bigint NOT NULL 
        REFERENCES handling_units(id) 
        ON DELETE CASCADE,
    allocation_id bigint NOT NULL 
        REFERENCES inventory_allocations(id) 
        ON DELETE RESTRICT,
    packed_quantity numeric(12, 4) NOT NULL CHECK (packed_quantity > 0)
);

CREATE INDEX idx_handling_units_order ON handling_units(outbound_order_id);
CREATE INDEX idx_handling_units_shipment ON handling_units(shipment_id);

